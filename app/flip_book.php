<script>
const episodes = <?php echo json_encode($episodes, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES); ?>;

let currentEpisodeIndex = 0;
let currentPageIndex = 0;
let currentMode = 'flip';

const heroCover = document.getElementById('heroCover');
const heroDescription = document.getElementById('heroDescription');
const featuredTitle = document.getElementById('featuredTitle');
const featuredTheme = document.getElementById('featuredTheme');
const featuredDesc = document.getElementById('featuredDesc');
const viewerTitle = document.getElementById('viewerTitle');
const thumbGrid = document.getElementById('thumbGrid');
const libraryGrid = document.getElementById('libraryGrid');
const flipImage = document.getElementById('flipImage');
const flipCard = document.getElementById('flipCard');
const pageNow = document.getElementById('pageNow');
const pageTotal = document.getElementById('pageTotal');
const prevBtn = document.getElementById('prevBtn');
const nextBtn = document.getElementById('nextBtn');
const scrollStack = document.getElementById('scrollStack');
const flipView = document.getElementById('flipView');
const scrollView = document.getElementById('scrollView');
const startReadingBtn = document.getElementById('startReadingBtn');
const toggleModeBtn = document.getElementById('toggleModeBtn');
const modeButtons = document.querySelectorAll('.mode-btn');

function getCurrentEpisode() {
    return episodes[currentEpisodeIndex];
}

function setMode(mode) {
    currentMode = mode;
    flipView.classList.toggle('active', mode === 'flip');
    scrollView.classList.toggle('active', mode === 'scroll');

    modeButtons.forEach(btn => {
        btn.classList.toggle('active', btn.dataset.mode === mode);
    });

    toggleModeBtn.textContent = mode === 'flip' ? '스크롤 보기' : '페이지 보기';
}

function renderThumbs() {
    const ep = getCurrentEpisode();
    thumbGrid.innerHTML = ep.pages.map((page, idx) => `
        <button class="thumb ${idx === currentPageIndex ? 'active' : ''}" data-page="${idx}">
            <img src="${page}" alt="thumb ${idx + 1}">
            <span>PAGE ${idx + 1}</span>
        </button>
    `).join('');

    thumbGrid.querySelectorAll('.thumb').forEach(btn => {
        btn.addEventListener('click', () => {
            currentPageIndex = Number(btn.dataset.page);
            renderViewer('next');
        });
    });
}

function renderLibrary() {
    libraryGrid.innerHTML = episodes.map((ep, idx) => `
        <article class="episode-card ${idx === currentEpisodeIndex ? 'active' : ''}" data-episode="${idx}">
            <div class="episode-cover">
                <div class="episode-topbar">
                    <span class="badge">THEME ${String(ep.id).padStart(2, '0')}</span>
                    ${idx === currentEpisodeIndex ? '<span class="badge light">NOW READING</span>' : ''}
                </div>
                <img src="${ep.cover}" alt="${ep.title}">
                <div class="episode-meta">
                    <div class="theme-text">${ep.theme}</div>
                    <h3>${ep.title}</h3>
                    <p>${ep.description}</p>
                </div>
            </div>
        </article>
    `).join('');

    libraryGrid.querySelectorAll('.episode-card').forEach(card => {
        card.addEventListener('click', () => {
            currentEpisodeIndex = Number(card.dataset.episode);
            currentPageIndex = 0;
            renderAll();
            document.querySelector('.viewer').scrollIntoView({ behavior: 'smooth', block: 'start' });
        });
    });
}

function renderViewer(direction = 'next') {
    const ep = getCurrentEpisode();
    const page = ep.pages[currentPageIndex];

    featuredTitle.textContent = ep.title;
    featuredTheme.textContent = ep.theme;
    featuredDesc.textContent = ep.description;
    viewerTitle.textContent = ep.title;
    heroDescription.textContent = ep.description;
    heroCover.style.backgroundImage = `url('${ep.cover}')`;

    pageNow.textContent = currentPageIndex + 1;
    pageTotal.textContent = ep.pages.length;
    prevBtn.disabled = currentPageIndex === 0;
    nextBtn.disabled = currentPageIndex === ep.pages.length - 1;

    flipCard.classList.remove('animating-next', 'animating-prev');
    void flipCard.offsetWidth;
    flipCard.classList.add(direction === 'prev' ? 'animating-prev' : 'animating-next');

    flipImage.src = page;
    flipImage.alt = ep.title + ' page ' + (currentPageIndex + 1);

    scrollStack.innerHTML = ep.pages.map((src, idx) => `
        <div class="scroll-item">
            <img src="${src}" alt="${ep.title} scroll ${idx + 1}">
        </div>
    `).join('');

    renderThumbs();
}

function renderAll(direction = 'next') {
    renderLibrary();
    renderViewer(direction);
}

prevBtn.addEventListener('click', () => {
    if (currentPageIndex > 0) {
        currentPageIndex -= 1;
        renderViewer('prev');
    }
});

nextBtn.addEventListener('click', () => {
    const ep = getCurrentEpisode();
    if (currentPageIndex < ep.pages.length - 1) {
        currentPageIndex += 1;
        renderViewer('next');
    }
});

modeButtons.forEach(btn => {
    btn.addEventListener('click', () => setMode(btn.dataset.mode));
});

toggleModeBtn.addEventListener('click', () => {
    setMode(currentMode === 'flip' ? 'scroll' : 'flip');
});

startReadingBtn.addEventListener('click', () => {
    document.querySelector('.viewer').scrollIntoView({ behavior: 'smooth', block: 'start' });
});

document.addEventListener('keydown', (e) => {
    if (e.key === 'ArrowLeft') prevBtn.click();
    if (e.key === 'ArrowRight') nextBtn.click();
});

setMode('flip');
renderAll();
</script>
